#!/usr/bin/env python3
"""
Generate the firmware secret headers from the .env file in the repo root.

    cp .env.example .env      # once, then edit .env
    python3 tools/make_secrets.py

Writes (both gitignored):
    src/secrets.h                  ESP32:   WIFI_SSID, WIFI_PASSWORD, WS_HOST
    esp8266_vitals/src/secrets.h   ESP8266: WIFI_SSID, WIFI_PASSWORD

Firmware cannot read .env at runtime (the values are compiled in), so this
script is the bridge. Re-run it whenever you change .env, then re-upload.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REQUIRED = ("WIFI_SSID", "WIFI_PASSWORD", "LAPTOP_IP")


def read_env(path: Path) -> dict:
    env = {}
    for n, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if "=" not in line:
            sys.exit(f"{path.name}:{n}: expected KEY=value")
        key, value = line.split("=", 1)
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
            value = value[1:-1]                       # allow KEY="value with spaces"
        env[key.strip()] = value
    return env


def c_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def header(board: str, defines: dict) -> str:
    lines = ["#pragma once",
             f"// {board} secrets - GENERATED by tools/make_secrets.py from .env.",
             "// Do not commit (gitignored). Edit .env and re-run the script instead.", ""]
    lines += [f"#define {k:<14} {c_str(v)}" for k, v in defines.items()]
    return "\n".join(lines) + "\n"


def main():
    env_path = ROOT / ".env"
    if not env_path.exists():
        sys.exit("No .env found. Run:  cp .env.example .env   then edit it and run this again.")
    env = read_env(env_path)
    missing = [k for k in REQUIRED if not env.get(k)]
    if missing:
        sys.exit(f".env is missing: {', '.join(missing)}")
    if env["WIFI_SSID"] == "your-wifi-name":
        sys.exit(".env still has the example values - put your real WiFi name/password in it.")

    out = {
        ROOT / "src" / "secrets.h": header("ESP32", {
            "WIFI_SSID": env["WIFI_SSID"], "WIFI_PASSWORD": env["WIFI_PASSWORD"],
            "WS_HOST": env["LAPTOP_IP"]}),
        ROOT / "esp8266_vitals" / "src" / "secrets.h": header("ESP8266", {
            "WIFI_SSID": env["WIFI_SSID"], "WIFI_PASSWORD": env["WIFI_PASSWORD"]}),
    }
    for path, text in out.items():
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    print(f"WiFi '{env['WIFI_SSID']}', laptop {env['LAPTOP_IP']}. Now re-upload both sketches.")


if __name__ == "__main__":
    main()
